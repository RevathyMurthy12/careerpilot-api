
import os
import sqlite3

import psycopg
from psycopg.rows import dict_row
from fastapi import FastAPI, HTTPException, status
from pydantic import BaseModel, ConfigDict, Field
from typing import Literal


# Database configuration
DATABASE = "careerpilot.db"
DATABASE_URL = os.getenv("DATABASE_URL")

app = FastAPI(title="CareerPilot API")


# Connect to PostgreSQL on Render or SQLite locally
def get_connection():
    if DATABASE_URL:
        database_url = DATABASE_URL.replace(
            "postgres://", "postgresql://", 1
        )
        return psycopg.connect(
            database_url,
            row_factory=dict_row
        )

    connection = sqlite3.connect(DATABASE)
    connection.row_factory = sqlite3.Row
    return connection


# Execute SQL with the correct placeholder for each database
def execute_query(connection, query, parameters=()):
    if DATABASE_URL:
        query = query.replace("?", "%s")

    return connection.execute(query, parameters)


# Create the database table
def create_table():
    connection = get_connection()

    try:
        if DATABASE_URL:
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS applications (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    company TEXT NOT NULL,
                    role TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'Applied'
                )
                """
            )
        else:
            execute_query(
                connection,
                """
                CREATE TABLE IF NOT EXISTS applications (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    company TEXT NOT NULL,
                    role TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'Applied'
                )
                """
            )

        connection.commit()
    finally:
        connection.close()


create_table()


# Validate incoming application data
class JobApplication(BaseModel):
    model_config = ConfigDict(str_strip_whitespace=True)

    company: str = Field(min_length=1, max_length=100)
    role: str = Field(min_length=1, max_length=100)
    status: Literal[
        "Applied",
        "Interview",
        "Selected",
        "Rejected",
        "Withdrawn"
    ] = "Applied"


# READ: Get all applications
@app.get("/applications")
def get_applications():
    connection = get_connection()

    try:
        rows = execute_query(
            connection,
            "SELECT * FROM applications ORDER BY id"
        ).fetchall()

        return [dict(row) for row in rows]
    finally:
        connection.close()


# CREATE: Add a new application
@app.post("/applications", status_code=status.HTTP_201_CREATED)
def create_application(application: JobApplication):
    connection = get_connection()

    try:
        if DATABASE_URL:
            cursor = execute_query(
                connection,
                """
                INSERT INTO applications (company, role, status)
                VALUES (?, ?, ?)
                RETURNING id
                """,
                (application.company, application.role, application.status)
            )
            new_id = cursor.fetchone()["id"]

        else:
            cursor = execute_query(
                connection,
                """
                INSERT INTO applications (company, role, status)
                VALUES (?, ?, ?)
                """,
                (application.company, application.role, application.status)
            )
            new_id = cursor.lastrowid

        connection.commit()

        row = execute_query(
            connection,
            "SELECT * FROM applications WHERE id = ?",
            (new_id,)
        ).fetchone()

        return {
            "message": "Application created successfully",
            "application": dict(row)
        }
    finally:
        connection.close()


# UPDATE: Change an existing application
@app.put("/applications/{application_id}")
def update_application(
    application_id: int,
    application: JobApplication
):
    connection = get_connection()

    try:
        cursor = execute_query(
            connection,
            """
            UPDATE applications
            SET company = ?, role = ?, status = ?
            WHERE id = ?
            """,
            (
                application.company,
                application.role,
                application.status,
                application_id
            )
        )

        if cursor.rowcount == 0:
            raise HTTPException(
                status_code=404,
                detail="Application not found"
            )

        connection.commit()

        row = execute_query(
            connection,
            "SELECT * FROM applications WHERE id = ?",
            (application_id,)
        ).fetchone()

        return {
            "message": "Application updated successfully",
            "application": dict(row)
        }
    finally:
        connection.close()


# DELETE: Remove an application
@app.delete("/applications/{application_id}")
def delete_application(application_id: int):
    connection = get_connection()

    try:
        cursor = execute_query(
            connection,
            "DELETE FROM applications WHERE id = ?",
            (application_id,)
        )

        if cursor.rowcount == 0:
            raise HTTPException(
                status_code=404,
                detail="Application not found"
            )

        connection.commit()

        return {
            "message": "Application deleted successfully",
            "id": application_id
        }
    finally:
        connection.close()
